import secrets
from pathlib import Path
from typing import Annotated, Literal

from pydantic import AfterValidator, Field, NonNegativeInt
from pydantic_settings import BaseSettings, SettingsConfigDict

from .dictionaries import Transport


def check_factor(value: tuple[float, float, float]) -> tuple[float, float, float]:
    """Множитель отклонения: `(низ, мода, верх)` (PLAN 6.18).

    Проверка нужна потому, что у `random.triangular` порядок другой — `(низ, верх, мода)`, —
    и перепутанная тройка не падает, а молча считает прогноз по другому распределению.
    """
    low, mode, high = value
    if not 0 < low <= mode <= high:
        raise ValueError("множитель задаётся как (низ, мода, верх), низ больше нуля")
    return value


Factor = Annotated[tuple[float, float, float], AfterValidator(check_factor)]


class Settings(BaseSettings):
    """Настройки сервиса. В контейнере приходят из docker compose, локально — из .env в корне репозитория."""

    model_config = SettingsConfigDict(env_file=("../.env", ".env"), extra="ignore")

    mongo_url: str = "mongodb://localhost:27017"
    mongo_db: str = "planner"
    valhalla_url: str = "http://localhost:8002"
    # Матрица на весь набор — тысячи пар в одном запросе, это не две секунды /api/health.
    # 600, потому что велосипед считается дольше всех: на наборе с Каширой и Ступином
    # (84 точки, 7 056 пар, дальняя в 92 км от офиса) замерено 188 с против 47 с у пешехода
    # и 13 с у автомобиля. Прежних 120 с ему не хватало, и профиль молча уходил в прямую.
    valhalla_timeout: float = 600
    # Сколько пар «источник-цель» Valhalla берёт за раз. Значение должно совпадать с
    # service_limits.*.max_matrix_location_pairs в valhalla/custom_files/valhalla.json:
    # запрос сверх лимита отклоняется, поэтому большие наборы шлём кусками (PLAN 5.6).
    valhalla_max_matrix_pairs: int = 10_000
    # Пробок у Valhalla нет, для автомобиля закладываем их коэффициентом (PLAN 2.7, 3.3).
    car_traffic_factor: float = 1.3
    # Общественный транспорт — усреднённое время (PLAN 3.3, ответ 14): короткое плечо идётся
    # пешком, дальше берётся время автомобиля с множителем за остановки и непрямой маршрут
    # плюс ожидание с пересадками. Расписаний маршрутов мы не считаем и не обещаем.
    transit_walk_m: int = 1500
    transit_factor: float = 1.6
    transit_wait_sec: int = 720
    dgis_api_key: str = ""
    # Подсказки адресов (2ГИС Suggest API): сколько запросов к 2ГИС в минуту пропускает сервис.
    # Подсказка просится почти на каждое нажатие клавиши, а у демо-ключа свои лимиты — Routing
    # на нём сгорел за секунды при обещанных документацией 600 в минуту. Поэтому по умолчанию 0:
    # подсказки выключены, пока лимит ключа не сверен в Platform Manager.
    dgis_suggest_per_min: int = Field(default=0, ge=0)
    # Не чаще одного запроса за столько секунд: лимит в минуту не мешает пяти запросам уйти
    # за одну секунду, а лимит ключа в секунду нам не известен. Ранний запрос ждёт, а не
    # отклоняется — подсказка на последнюю паузу в наборе всё равно придёт.
    dgis_suggest_interval_sec: float = Field(default=1.0, ge=0)
    # Ассистент диспетчера (блок 42): YandexGPT через OpenAI-совместимый API Yandex AI Studio.
    # Пустой ключ — ассистент выключен, остальной экран работает как раньше. Модель — имя из
    # карточки в консоли (например `yandexgpt/rc`); в код оно не зашито, линейка у Яндекса меняется.
    yandex_api_key: str = ""
    yandex_folder_id: str = ""
    yandex_model: str = "yandexgpt/rc"
    # На один вызов, а вопрос — два вызова подряд: прокси перед API должен ждать больше двух тайм-аутов.
    yandex_timeout_sec: float = Field(default=60, gt=0)
    # Потолок ответа модели в токенах. Рассуждающая модель (gpt-oss) тратит на скрытые рассуждения
    # тот же лимит, и при малом значении ответ обрывается пустым. Это потолок, а не расход: платится
    # то, что модель написала. Вместе с запросом (до ~10 тыс. токенов на вопрос по плану) он должен
    # помещаться в окно модели: у YandexGPT Pro оно 32 тыс.
    yandex_max_tokens: int = Field(default=16000, gt=0)
    # Сколько рассуждать рассуждающей модели (gpt-oss) при ответе на вопрос по плану (разбор фразы
    # в JSON не затрагивается): `low` отвечает за 2 секунды, а по умолчанию
    # на части вопросов она зацикливается на рассуждении, упирается в потолок токенов за минуту с
    # лишним и не отвечает (3 из 10 на «почему заявка назначена именно так?»). Пусто — параметр не
    # отправляется: моделям без рассуждений он не нужен, а как они его примут, не проверено.
    yandex_reasoning_effort: Literal["", "low", "medium", "high"] = ""
    # Сколько знаков вложения ассистента уходит модели (блок 60): длиннее — обрезается с
    # пометкой. Вложений до трёх на сообщение, и все они едут в тот же запрос, что и план.
    assistant_attachment_chars: int = Field(default=15000, gt=0)
    # Трактовка окна заявки (PLAN 6.2). По умолчанию правило ТЗ: в окно попадает начало работы.
    # fit_in_window — правило Дополнений: работа целиком внутри окна.
    window_rule: Literal["start_in_window", "fit_in_window"] = "start_in_window"
    # Порядок критериев цели оптимизатора (PLAN 6.5). Смена бизнес-приоритетов — это
    # перестановка списка в optimizer.ORDERS, а не правка модели. По умолчанию авария
    # старше количества (ответ 15); count_first — буквальное чтение Дополнений, п. 2.
    objective_mode: Literal[
        "emergency_first",
        "count_first",
        "urgent_first",
        "priority_first",
        "rating_first",
    ] = "emergency_first"
    # Аварии вперёд (PLAN 6.5, блок 49): в `emergency_first` сначала решаются одни аварии —
    # как можно раньше, — затем весь день, где назначенные аварии обязательны и начинаются
    # не позже достигнутого плюс `emergency_slack_min`.
    objective_staged: bool = False
    emergency_slack_min: int = Field(default=15, gt=0)
    # Сколько единиц оборудования бригада берёт на день, по транспорту (PLAN 2.7, 6.2).
    # Норматива у заказчика нет, ориентир для пешего инженера — 1–2 единицы в рюкзаке;
    # транспорта нет в словаре — ограничения нет. Из .env задаётся JSON-ом. Ключи — из
    # справочника: опечатка вроде «pedestrian» иначе молча означала бы «без ограничения».
    equipment_capacity: dict[Transport, NonNegativeInt] = {
        Transport.BICYCLE: 3,
        Transport.PUBLIC_TRANSPORT: 2,
    }
    # Срок реакции на аварию, пришедшую днём (PLAN 6.12): на сетевую аварию организаторы
    # закладывают 1–2 часа, поэтому конец её окна — не позже начала окна плюс срок, а начало
    # окна само не раньше момента поступления.
    emergency_response_min: int = Field(default=120, gt=0)
    # Поиск OR-Tools останавливает предел числа решений (PLAN 6.5): одна и та же модель с
    # одним пределом проходит одну и ту же траекторию, поэтому план повторяется на любой
    # машине. Предел подобран замером блока 45: на машине разработки поиск укладывается в 20 с
    # на всех трёх участках (на «Юго-востоке», 83 заявки, — 14 с; 1 600 решений там — 29 с).
    solver_solution_limit: int = Field(default=800, ge=1)
    # Лимит времени — только страховка для медленной машины: остановленный им поиск
    # помечается `search.stoppedBy: time`, и повторяемость такого плана не обещана.
    solver_time_limit_sec: int = 60
    # Перепланирование короче: событие приходит в рабочем ритме диспетчера, а стартовым
    # решением подаётся прошлый план — искать с нуля солверу не приходится. Предел подобран
    # под 10 с на машине разработки (на «Юго-востоке» — 6,5 с), время — снова страховка.
    # Им же считается событие по варианту сравнения: от варианта наследуется порядок критериев.
    replan_solution_limit: int = Field(default=400, ge=1)
    replan_time_limit_sec: int = 30
    # Процессы для вариантов предпросмотра события (PLAN 6.12, блок 53): каждый вариант —
    # свой солвер на своём ядре, и три варианта ждутся как один. 1 — по очереди, в процессе
    # API: для слабой машины.
    solver_workers: int = Field(default=3, ge=1)
    # Прогноз опозданий (PLAN 6.18): прогоны дня со случайными отклонениями от норматива.
    # Seed фиксирован — два расчёта одного плана обязаны дать один прогноз. Прогонов хотя бы
    # один: ноль поделил бы на ноль в каждом расчёте плана, а не «отключил бы прогноз».
    forecast_runs: int = Field(default=200, ge=1)
    forecast_seed: int = 2026
    # Множители `(low, mode, high)` для `random.triangular`. Порядок здесь человеческий, а не
    # питоновский: в вызов они идут как `triangular(low, high, mode)`. Работы растягиваются
    # сильнее, чем ускоряются, переезды колеблются уже: пробки мы уже заложили в матрицы (2.7).
    forecast_work_factor: Factor = (0.8, 1.0, 1.6)
    forecast_travel_factor: Factor = (0.9, 1.0, 1.5)
    cors_origins: list[str] = ["http://localhost:3000"]
    # Ссылка клиента на оценку (PLAN 9.1, блок 70): подпись плана и заявки этим секретом,
    # без хранения. Не задан — случайный на запуск: общеизвестное умолчание из репозитория
    # позволило бы любому подписать оценку чужой заявки; цена — ссылки до перезапуска.
    rating_secret: str = Field(default_factory=lambda: secrets.token_urlsafe(32))
    # Адрес фронтенда, с которого клиент откроет ссылку: телефон `localhost` не откроет.
    public_base_url: str = "http://localhost:3000"
    # Наборы данных и примеры. В образ backend каталог не попадает
    # (он вне контекста сборки), в контейнер приходит томом — см. docker-compose.yml.
    data_dir: Path = Path(__file__).resolve().parents[2] / "data"


settings = Settings()
