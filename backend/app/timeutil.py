"""Единицы на границе API: «HH:MM» ⇄ секунды от полуночи, метры → километры.

Внутри алгоритма — целые секунды и метры, наружу — минуты и километры (PLAN 2.6).
Единственное место перевода в проекте, кроме мапперов.
"""

import re

CLOCK = re.compile(r"^([01]\d|2[0-3]):([0-5]\d)$")
DAY = 24 * 3600


def to_seconds(clock: str) -> int:
    """«10:30» -> 37800. Формат строгий: «9:00» и «25:00» — ошибка, а не догадка."""
    match = CLOCK.match(clock)
    if match is None:
        raise ValueError(f"время «{clock}» не в формате HH:MM")
    return int(match[1]) * 3600 + int(match[2]) * 60


def to_clock(seconds: int) -> str:
    """37800 -> «10:30». Секунды сверх минуты отбрасываются: наружу отдаём минуты (PLAN 2.6)."""
    if not 0 <= seconds < DAY:
        raise ValueError(f"{seconds} с — время вне суток")
    return f"{seconds // 3600:02d}:{seconds % 3600 // 60:02d}"


def to_clock_over_midnight(seconds: int) -> str:
    """86400 -> «24:00»: время, которое не уместилось в сутки.

    `to_clock` на таком времени падает — и правильно делает, в готовом плане его быть не
    может. Но причина неназначения (PLAN 6.8) и текст ошибки проверки (6.7) описывают как
    раз то, чего в плане нет: работу, которая закончилась бы за полночь. Падать на ней нельзя.
    """
    return f"{seconds // 3600:02d}:{seconds % 3600 // 60:02d}"


def to_km(meters: int) -> float:
    """5049 -> 5.0. Одна десятая — та точность, в которой километры уходят наружу (PLAN 5.2)."""
    return round(meters / 1000, 1)


def to_minutes(seconds: int) -> int:
    """95 -> 2. Половина минуты округляется вверх, без float: наружу уходят целые минуты."""
    return (seconds + 30) // 60
